# Finish a working session on main: run the gate, commit, push.
#
#     powershell -ExecutionPolicy Bypass -File .\finish-session.ps1 -Message "what changed"
#     powershell -ExecutionPolicy Bypass -File .\finish-session.ps1 -MessageFile .\msg.txt
#     powershell -ExecutionPolicy Bypass -File .\finish-session.ps1 -Message "..." -DryRun
#
# Nothing reaches the remote until the whole gate has passed and you have confirmed the
# file list. -DryRun stops after showing what would be committed.
#
# `graphify-out/` is never staged by this script. AGENTS.md rule 9: only the integration
# lead regenerates it, at the weekly session, in a commit containing nothing else. Use
# `-Graph` to make exactly that commit and nothing else.

[CmdletBinding()]
param(
    [string]$Message,
    [string]$MessageFile,
    [switch]$Graph,
    [switch]$DryRun
)

$ErrorActionPreference = 'Stop'

function Step($label)  { Write-Host "`n=== $label ===" -ForegroundColor Cyan }
function Fail($label)  { if ($LASTEXITCODE -ne 0) { throw "$label failed (exit $LASTEXITCODE)" } }
function Note($text)   { Write-Host $text -ForegroundColor DarkGray }

# --------------------------------------------------------------------------- arguments

if ($Graph -and ($Message -or $MessageFile)) {
    throw 'Use -Graph on its own: the graph commit writes its own message and contains nothing else.'
}
if (-not $Graph) {
    if ($Message -and $MessageFile) { throw 'Pass -Message or -MessageFile, not both.' }
    if (-not $Message -and -not $MessageFile) {
        throw 'Pass -Message "what changed" or -MessageFile <path>. A commit with no message is not a commit.'
    }
    if ($MessageFile -and -not (Test-Path $MessageFile)) { throw "No message file at $MessageFile" }
}

# ------------------------------------------------------------------------------ on main

Step 'Branch'
$branch = git rev-parse --abbrev-ref HEAD
Fail 'git rev-parse'
Write-Host "On $branch"
if ($branch -ne 'main') {
    throw "This script commits to main; you are on $branch. Switch, or merge your branch first."
}

Step 'Fetching, so we do not push onto a stale main'
git fetch origin main
Fail 'git fetch'
$behind = git rev-list --count HEAD..origin/main
Fail 'git rev-list'
if ([int]$behind -gt 0) {
    throw "main is $behind commit(s) behind origin/main. Pull and re-run."
}

Step 'Secrets'
git check-ignore -q .env
if ($LASTEXITCODE -ne 0) { throw '.env is not git-ignored. Stop and fix .gitignore before committing.' }
Note '.env is ignored.'

# ------------------------------------------------------------------- the graph-only path

if ($Graph) {
    Step 'Staging graphify-out only (AGENTS.md rule 9)'
    git reset -q
    Fail 'git reset'
    git add graphify-out
    Fail 'git add graphify-out'
    $staged = git diff --cached --name-only
    Fail 'git diff --cached'
    if (-not $staged) { Write-Host 'Nothing to commit: the graph is unchanged.'; exit 0 }
    $staged | ForEach-Object { Write-Host "  $_" }
    if ($DryRun) { Note 'Dry run: stopping before commit.'; exit 0 }
    git commit -m 'Refresh the code graph' -m 'Regenerated by the integration lead at the weekly session. Nothing else is in this commit.'
    Fail 'git commit'
    git push origin main
    Fail 'git push'
    Write-Host "`nGraph pushed." -ForegroundColor Green
    exit 0
}

# ---------------------------------------------------------------------------- the gate

Step 'Running the gate'
uv run python -m packs.build --check
Fail 'packs.build --check'
uv run python scripts/build_team_tasks.py --check
Fail 'build_team_tasks --check'
uv run ruff check .
Fail 'ruff check'
uv run ruff format --check .
Fail 'ruff format --check'
uv run mypy core modules corpus
Fail 'mypy'
uv run pytest -q
Fail 'pytest'

# --------------------------------------------------------------------------- the commit

Step 'Staging everything except graphify-out'
git reset -q
Fail 'git reset'
git add -A -- . ':!graphify-out'
Fail 'git add'

$staged = git diff --cached --name-only
Fail 'git diff --cached'
if (-not $staged) { Write-Host 'Nothing to commit.'; exit 0 }

Write-Host "$(@($staged).Count) file(s):"
$staged | ForEach-Object { Write-Host "  $_" }

$leftBehind = git status --short | Where-Object { $_ -match 'graphify-out' }
if ($leftBehind) {
    Note ''
    Note 'graphify-out/ has changed and is deliberately NOT in this commit.'
    Note 'Commit it on its own with:  .\finish-session.ps1 -Graph'
}

if ($DryRun) { Note "`nDry run: stopping before commit."; exit 0 }

Step 'Commit'
if ($MessageFile) { git commit -F $MessageFile } else { git commit -m $Message }
Fail 'git commit'
git log --oneline -1
Fail 'git log'

# ----------------------------------------------------------------------------- the push

Step 'Push'
$answer = Read-Host "Push $(git rev-list --count origin/main..HEAD) commit(s) to origin/main? [y/N]"
if ($answer -ne 'y') {
    Note 'Not pushed. The commit is local; push it yourself when ready.'
    exit 0
}
git push origin main
Fail 'git push'

Write-Host "`nPushed." -ForegroundColor Green
