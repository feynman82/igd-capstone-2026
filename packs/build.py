"""Generate everything downstream of the core document catalogue, and check every pack against it.

    python -m packs.build            # regenerate
    python -m packs.build --check    # fail if anything is stale (this is the CI gate)

One YAML in (ADR 0017), four things out:

    core/document_schemas.py                 Pydantic models the extractor constrains on
    corpus/register/core_columns.csv         what the core can extract, for reference
    corpus/register/batch.template.csv       the header a batch register is copied from
    docs/field-dictionary.md                 every field in the system, for humans

Every `packs/<id>/pack.yaml` is validated too, and the document types, fields and categories it
names are checked against the catalogue, so a pack naming something the core does not declare
fails here as well as when packs load.

Generating the register headers from the same file the extractor uses is the whole point:
the catalogue's field names and Desmond's column names cannot drift apart, because there is only
one place they are written down.
"""

from __future__ import annotations

import argparse
import difflib
import sys
import textwrap
from pathlib import Path

import yaml

from core.contracts import FACT_COLUMN, DocumentCatalog, PackManifest

PACKS_DIR = Path("packs")
CATALOG = Path("core/documents.yaml")
SCHEMAS = Path("core/document_schemas.py")
REGISTER_DIR = Path("corpus/register")
COLUMNS = REGISTER_DIR / "core_columns.csv"
DICTIONARY = Path("docs/field-dictionary.md")
BATCH_TEMPLATE = REGISTER_DIR / "batch.template.csv"
CORE = "core"  # the pack_id every register row and every fact carries

PY_TYPE = {
    "string": "str",
    "identifier": "str",
    "person": "str",
    "money": "Decimal",
    "integer": "int",
    "percent": "float",
    "date": "date",
    "month": "str",
    "enum": "str",
    "boolean": "bool",
}
# Constraints the extraction model is held to at decode time.
PY_FIELD_ARGS = {
    "month": 'pattern=r"^\\d{4}-(0[1-9]|1[0-2])$"',
    "money": "ge=0",
    "percent": "ge=0, le=100",
    "integer": "ge=0",
}
BANNER = "# GENERATED by `python -m packs.build` from core/documents.yaml. Do not edit by hand.\n"
LINE_LENGTH = 100  # generated files obey the repository line length


def load_catalog(path: Path = CATALOG) -> DocumentCatalog:
    catalog = DocumentCatalog.model_validate(yaml.safe_load(path.read_text(encoding="utf-8")))
    for doc_type, spec in catalog.document_types.items():
        for f in spec.fields:
            # ponytail: no field repeats yet; PR 7 adds generation and extraction for them.
            if f.type == "labelled_money" or f.repeats:
                raise SystemExit(
                    f"{path}: {doc_type}.{f.name} uses labelled_money or repeats, which "
                    "packs.build cannot generate yet"
                )
    return catalog


def load(pack_dir: Path) -> PackManifest:
    raw = yaml.safe_load((pack_dir / "pack.yaml").read_text(encoding="utf-8"))
    return PackManifest.model_validate(raw)


def _class_name(doc_type: str) -> str:
    return "".join(part.capitalize() for part in doc_type.split("_"))


QUOTES = chr(34) * 3


def _docstring(text: str, indent: str) -> list[str]:
    """One line when it fits the line length, otherwise a wrapped block."""
    single = f"{indent}{QUOTES}{text}.{QUOTES}"
    if len(single) <= LINE_LENGTH:
        return [single]
    body = textwrap.wrap(f"{text}.", LINE_LENGTH - len(indent))
    first, rest = body[0], body[1:]
    return [f"{indent}{QUOTES}{first}", *(f"{indent}{line}" for line in rest), indent + QUOTES]


def _field_line(name: str, py: str, args: list[str]) -> list[str]:
    """One line when it fits, otherwise one keyword argument per line."""
    joined = ", ".join(args)
    single = f"    {name}: {py} = Field({joined})"
    if len(single) <= LINE_LENGTH:
        return [single]
    return [f"    {name}: {py} = Field(", *(f"        {arg}," for arg in args), "    )"]


def render_schemas(c: DocumentCatalog) -> str:
    has_enum = any(
        f.type == "enum" and f.values for spec in c.document_types.values() for f in spec.fields
    )
    lines = [
        BANNER,
        '"""Extraction models for the core document catalogue."""\n',
        "from __future__ import annotations\n",
        "from datetime import date",
        "from decimal import Decimal",
        *(["from typing import Literal"] if has_enum else []),
        "",
        "from pydantic import BaseModel, ConfigDict, Field\n",
        "",
    ]
    names = []
    for doc_type, spec in c.document_types.items():
        cls = _class_name(doc_type)
        names.append((doc_type, cls))
        lines += [
            f"class {cls}(BaseModel):",
            *_docstring(spec.description, "    "),
            "",
            '    model_config = ConfigDict(extra="forbid")',
            "",
        ]
        for f in spec.fields:
            if f.type == "enum" and f.values:
                py = "Literal[" + ", ".join(f'"{v}"' for v in f.values) + "]"
            else:
                py = PY_TYPE[f.type]
            args = [f'description="{f.description}"']
            if extra := PY_FIELD_ARGS.get(f.type):
                args.insert(0, extra)
            if not f.required:
                py = f"{py} | None"
                args.insert(0, "default=None")
            lines += _field_line(f.name, py, args)
        lines += ["", ""]

    lines += [
        "# doc_type -> model, used by the ingestion worker to pick a decode constraint.",
        "MODELS: dict[str, type[BaseModel]] = {",
        *[f'    "{dt}": {cls},' for dt, cls in names],
        "}",
        "",
        "# field name -> the facts column it is stored in, used by the extractor and the scorer.",
        "FACT_COLUMNS: dict[str, str] = {",
        *sorted(
            {
                f'    "{f.name}": "{FACT_COLUMN[f.type]}",'
                for spec in c.document_types.values()
                for f in spec.fields
            }
        ),
        "}",
        "",
    ]
    return "\n".join(lines)


def _header(c: DocumentCatalog) -> str:
    """Every field of every document type, once each, in declared order."""
    fixed = ["doc_id", "doc_type", "pack_id", "issued_date", "subject", "tier"]
    seen: list[str] = []
    for spec in c.document_types.values():
        for f in spec.fields:
            if f.name not in seen:
                seen.append(f.name)
    return ",".join(fixed + seen + ["field_pages", "notes"])


def render_register_columns(c: DocumentCatalog) -> str:
    """The header row Desmond fills in.

    Long format: one row per document, and a column for every field the core can extract.
    A field that does not apply to a document type is left empty.
    """
    guide = [
        "# Core document catalogue — register columns. GENERATED by `python -m packs.build`.",
        "# One row per document. Fill every column that applies to the document type.",
        "# doc_type must be one of: " + ", ".join(sorted(c.document_types)),
        f"# pack_id is always: {CORE}",
        "# tier must be one of: clean, scanned, photo",
        "# Dates are YYYY-MM-DD. Money is a plain number, no currency symbol, two decimals.",
        "# Identifiers are copied exactly as printed: no spaces removed, no case changed.",
        "#",
        "# field_pages: which page each value is PRINTED on, for the fields not on page 1.",
        "#   Semicolon-separated name=page, 1-based: expiry_date=2;premium_payable=2",
        "#   Anything left out is page 1, so a single-page document leaves this empty.",
        "#   Filled AFTER the mail merge, when the page layout exists — it is the one column",
        "#   that cannot be known while the register is being written. It is what lets a",
        "#   golden-set question say which page the answer should be cited from.",
        "#",
    ]
    for doc_type, spec in c.document_types.items():
        req = [f.name for f in spec.fields if f.required]
        opt = [f.name for f in spec.fields if not f.required]
        guide.append(f"# {doc_type}: required = {', '.join(req)}")
        if opt:
            guide.append(f"#   {' ' * len(doc_type)}optional = {', '.join(opt)}")
    guide.append("#")
    return "\n".join(guide) + "\n" + _header(c) + "\n"


def render_batch_template(c: DocumentCatalog) -> str:
    """The header a batch register starts from: every field of every document type.

    A batch is a household's documents, so it mixes payslips and policy schedules in one file
    with one row each. `core_columns.csv` shows what the core can extract; this is the one to
    copy and fill.
    """
    guide = [
        "# Batch register template. GENERATED by `python -m packs.build`. Do not edit by hand.",
        "#",
        "# Copy this file to corpus/register/<batch>.csv and fill one row per document, then:",
        "#     uv run python -m corpus.validate corpus/register/<batch>.csv",
        "#",
        "# Leave these guide lines in place if you like — the validator skips them.",
        "# Every column below is a field core/documents.yaml declares. Fill the ones that",
        "# apply to the row's doc_type and leave the rest empty.",
        "#",
        f"# pack_id is always: {CORE}",
        "# tier must be one of: clean, scanned, photo",
        "# Dates are YYYY-MM-DD. Money is a plain number, no currency symbol, two decimals.",
        "# Identifiers are copied exactly as printed: no spaces removed, no case changed.",
        "#",
        "# field_pages: which page each value is PRINTED on, for the fields not on page 1.",
        "#   Semicolon-separated name=page, 1-based: expiry_date=2;premium_payable=2",
        "#   Anything left out is page 1, so a single-page document leaves this empty.",
        "#   Fill it AFTER the mail merge, when the page layout exists.",
        "#",
        "# Document types (core/documents.yaml)",
    ]
    for doc_type, spec in c.document_types.items():
        req = [f.name for f in spec.fields if f.required]
        guide.append(f"#   {doc_type}: required = {', '.join(req)}")
    guide.append("#")
    return "\n".join(guide) + "\n" + _header(c) + "\n"


def render_dictionary(c: DocumentCatalog) -> str:
    out = [
        "<!-- GENERATED by `python -m packs.build`. Do not edit by hand. -->",
        "# Field dictionary",
        "",
        "Every extractable field in the system. A field name is simultaneously the column",
        "header in the corpus register, the `facts.key` it is stored under, and the attribute",
        "on the extraction model. Renaming one renames all three, so rename in",
        "`core/documents.yaml` and regenerate.",
        "",
        "## Core document catalogue (`core/documents.yaml`)",
        "",
    ]
    for doc_type, spec in c.document_types.items():
        out += [
            f"### `{doc_type}`",
            "",
            spec.description + ".",
            "",
            "| Field | Type | Required | Stored in | Meaning |",
            "|---|---|---|---|---|",
        ]
        for f in spec.fields:
            out.append(
                f"| `{f.name}` | {f.type} | {'yes' if f.required else 'no'} "
                f"| `facts.{FACT_COLUMN[f.type]}` | {f.description} |"
            )
        out.append("")
    return "\n".join(out)


def _write(path: Path, content: str, check: bool, stale: list[str]) -> None:
    current = path.read_text(encoding="utf-8") if path.exists() else ""
    if current == content:
        return
    if check:
        diff = difflib.unified_diff(
            current.splitlines(),
            content.splitlines(),
            fromfile=f"{path} (committed)",
            tofile=f"{path} (expected)",
            lineterm="",
            n=1,
        )
        stale.append(f"{path}\n" + "\n".join(list(diff)[:20]))
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"wrote {path}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if any generated file is stale")
    args = ap.parse_args()

    catalog = load_catalog()
    stale: list[str] = []
    checked = 0
    for d in sorted(d for d in PACKS_DIR.iterdir() if (d / "pack.yaml").exists()):
        if d.name.startswith("_"):
            continue
        m = load(d)
        if m.id != d.name:
            raise SystemExit(f"{d}/pack.yaml: id {m.id!r} does not match directory name {d.name!r}")
        try:
            m.check_against(catalog)
        except ValueError as error:
            raise SystemExit(f"{d}/pack.yaml: {error}") from error
        checked += 1

    _write(SCHEMAS, render_schemas(catalog), args.check, stale)
    _write(COLUMNS, render_register_columns(catalog), args.check, stale)
    _write(BATCH_TEMPLATE, render_batch_template(catalog), args.check, stale)
    _write(DICTIONARY, render_dictionary(catalog), args.check, stale)

    # What the build generated per pack before the core owned documents (ADR 0017).
    leftovers = [*PACKS_DIR.glob("*/schemas.py"), *REGISTER_DIR.glob("*_columns.csv")]
    for leftover in sorted(p for p in leftovers if p != COLUMNS):
        if args.check:
            stale.append(f"{leftover}\n  is no longer generated; delete it")
        else:
            leftover.unlink()
            print(f"removed {leftover}")

    if stale:
        print("Generated files are out of date. Run `python -m packs.build` and commit:\n")
        for s in stale:
            print(s, "\n")
        sys.exit(1)
    print(f"{len(catalog.document_types)} document type(s) and {checked} pack(s) up to date")


if __name__ == "__main__":
    main()
