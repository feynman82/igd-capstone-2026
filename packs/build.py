"""Generate everything downstream of a pack.yaml.

    python -m packs.build            # regenerate
    python -m packs.build --check    # fail if anything is stale (this is the CI gate)

One YAML in, three things out:

    packs/<id>/schemas.py                    Pydantic models the extractor constrains on
    corpus/register/<id>_columns.csv         what one pack can extract, for reference
    corpus/register/batch.template.csv       the header a batch register is copied from
    docs/field-dictionary.md                 every field in the system, for humans

Generating the register headers from the same file the extractor uses is the whole point:
Zee's field names and Desmond's column names cannot drift apart, because there is only one
place they are written down.
"""

from __future__ import annotations

import argparse
import difflib
import sys
import textwrap
from pathlib import Path

import yaml

from core.contracts import FACT_COLUMN, PackManifest

PACKS_DIR = Path("packs")
REGISTER_DIR = Path("corpus/register")
DICTIONARY = Path("docs/field-dictionary.md")
BATCH_TEMPLATE = Path("corpus/register/batch.template.csv")

PY_TYPE = {
    "string": "str",
    "identifier": "str",
    "person": "str",
    "money": "Decimal",
    "integer": "int",
    "percent": "float",
    "date": "date",
    "month": "str",
    "enum": "str",
    "boolean": "bool",
}
# Constraints the extraction model is held to at decode time.
PY_FIELD_ARGS = {
    "month": 'pattern=r"^\\d{4}-(0[1-9]|1[0-2])$"',
    "money": "ge=0",
    "percent": "ge=0, le=100",
    "integer": "ge=0",
}
BANNER = "# GENERATED by `python -m packs.build` from pack.yaml. Do not edit by hand.\n"
LINE_LENGTH = 100  # generated files obey the repository line length


def load(pack_dir: Path) -> PackManifest:
    raw = yaml.safe_load((pack_dir / "pack.yaml").read_text(encoding="utf-8"))
    return PackManifest.model_validate(raw)


def _class_name(doc_type: str) -> str:
    return "".join(part.capitalize() for part in doc_type.split("_"))


QUOTES = chr(34) * 3


def _docstring(text: str, indent: str) -> list[str]:
    """One line when it fits the line length, otherwise a wrapped block."""
    single = f"{indent}{QUOTES}{text}.{QUOTES}"
    if len(single) <= LINE_LENGTH:
        return [single]
    body = textwrap.wrap(f"{text}.", LINE_LENGTH - len(indent))
    first, rest = body[0], body[1:]
    return [f"{indent}{QUOTES}{first}", *(f"{indent}{line}" for line in rest), indent + QUOTES]


def _field_line(name: str, py: str, args: list[str]) -> list[str]:
    """One line when it fits, otherwise one keyword argument per line."""
    joined = ", ".join(args)
    single = f"    {name}: {py} = Field({joined})"
    if len(single) <= LINE_LENGTH:
        return [single]
    return [f"    {name}: {py} = Field(", *(f"        {arg}," for arg in args), "    )"]


def render_schemas(m: PackManifest) -> str:
    has_enum = any(
        f.type == "enum" and f.values for spec in m.document_types.values() for f in spec.fields
    )
    lines = [
        BANNER,
        f'"""Extraction models for the {m.display_name} pack."""\n',
        "from __future__ import annotations\n",
        "from datetime import date",
        "from decimal import Decimal",
        *(["from typing import Literal"] if has_enum else []),
        "",
        "from pydantic import BaseModel, ConfigDict, Field\n",
        "",
    ]
    names = []
    for doc_type, spec in m.document_types.items():
        cls = _class_name(doc_type)
        names.append((doc_type, cls))
        lines += [
            f"class {cls}(BaseModel):",
            *_docstring(spec.description, "    "),
            "",
            '    model_config = ConfigDict(extra="forbid")',
            "",
        ]
        for f in spec.fields:
            if f.type == "enum" and f.values:
                py = "Literal[" + ", ".join(f'"{v}"' for v in f.values) + "]"
            else:
                py = PY_TYPE[f.type]
            args = [f'description="{f.description}"']
            if extra := PY_FIELD_ARGS.get(f.type):
                args.insert(0, extra)
            if not f.required:
                py = f"{py} | None"
                args.insert(0, "default=None")
            lines += _field_line(f.name, py, args)
        lines += ["", ""]

    lines += [
        "# doc_type -> model, used by the ingestion worker to pick a decode constraint.",
        "MODELS: dict[str, type[BaseModel]] = {",
        *[f'    "{dt}": {cls},' for dt, cls in names],
        "}",
        "",
        "# field name -> the facts column it is stored in, used by the extractor and the scorer.",
        "FACT_COLUMNS: dict[str, str] = {",
        *sorted(
            {
                f'    "{f.name}": "{FACT_COLUMN[f.type]}",'
                for spec in m.document_types.values()
                for f in spec.fields
            }
        ),
        "}",
        "",
    ]
    return "\n".join(lines)


def render_register_columns(m: PackManifest) -> str:
    """The header row Desmond fills in, one file per pack.

    Long format: one row per document, and a column for every field this pack can extract.
    A field that does not apply to a document type is left empty.
    """
    fixed = ["doc_id", "doc_type", "pack_id", "issued_date", "subject", "tier"]
    seen: list[str] = []
    for spec in m.document_types.values():
        for f in spec.fields:
            if f.name not in seen:
                seen.append(f.name)
    header = ",".join(fixed + seen + ["field_pages", "notes"])

    guide = [
        f"# {m.display_name} — register columns. GENERATED by `python -m packs.build`.",
        "# One row per document. Fill every column that applies to the document type.",
        "# doc_type must be one of: " + ", ".join(sorted(m.document_types)),
        "# tier must be one of: clean, scanned, photo",
        "# Dates are YYYY-MM-DD. Money is a plain number, no currency symbol, two decimals.",
        "# Identifiers are copied exactly as printed: no spaces removed, no case changed.",
        "#",
        "# field_pages: which page each value is PRINTED on, for the fields not on page 1.",
        "#   Semicolon-separated name=page, 1-based: expiry_date=2;premium_payable=2",
        "#   Anything left out is page 1, so a single-page document leaves this empty.",
        "#   Filled AFTER the mail merge, when the page layout exists — it is the one column",
        "#   that cannot be known while the register is being written. It is what lets a",
        "#   golden-set question say which page the answer should be cited from.",
        "#",
    ]
    for doc_type, spec in m.document_types.items():
        req = [f.name for f in spec.fields if f.required]
        opt = [f.name for f in spec.fields if not f.required]
        guide.append(f"# {doc_type}: required = {', '.join(req)}")
        if opt:
            guide.append(f"#   {' ' * len(doc_type)}optional = {', '.join(opt)}")
    guide.append("#")
    return "\n".join(guide) + "\n" + header + "\n"


def render_batch_template(manifests: list[PackManifest]) -> str:
    """The header a batch register starts from: every field of every installed pack.

    A batch is not one pack's documents — it is a household's, so it mixes payslips and
    policy schedules in one file with one row each. The per-pack `<id>_columns.csv` files
    show what a pack can extract; this is the one to copy and fill, because hand-merging two
    generated headers is how a column name drifts from a field name.
    """
    fixed = ["doc_id", "doc_type", "pack_id", "issued_date", "subject", "tier"]
    seen: list[str] = []
    for m in manifests:
        for spec in m.document_types.values():
            for f in spec.fields:
                if f.name not in seen:
                    seen.append(f.name)

    guide = [
        "# Batch register template. GENERATED by `python -m packs.build`. Do not edit by hand.",
        "#",
        "# Copy this file to corpus/register/<batch>.csv and fill one row per document, then:",
        "#     uv run python -m corpus.validate corpus/register/<batch>.csv",
        "#",
        "# Leave these guide lines in place if you like — the validator skips them.",
        "# Every column below is a field some installed pack declares. Fill the ones that",
        "# apply to the row's doc_type and leave the rest empty.",
        "#",
        "# tier must be one of: clean, scanned, photo",
        "# Dates are YYYY-MM-DD. Money is a plain number, no currency symbol, two decimals.",
        "# Identifiers are copied exactly as printed: no spaces removed, no case changed.",
        "#",
        "# field_pages: which page each value is PRINTED on, for the fields not on page 1.",
        "#   Semicolon-separated name=page, 1-based: expiry_date=2;premium_payable=2",
        "#   Anything left out is page 1, so a single-page document leaves this empty.",
        "#   Fill it AFTER the mail merge, when the page layout exists.",
        "#",
    ]
    for m in manifests:
        guide.append(f"# {m.display_name} ({m.id})")
        for doc_type, spec in m.document_types.items():
            req = [f.name for f in spec.fields if f.required]
            guide.append(f"#   {doc_type}: required = {', '.join(req)}")
    guide.append("#")
    header = ",".join(fixed + seen + ["field_pages", "notes"])
    return "\n".join(guide) + "\n" + header + "\n"


def render_dictionary(manifests: list[PackManifest]) -> str:
    out = [
        "<!-- GENERATED by `python -m packs.build`. Do not edit by hand. -->",
        "# Field dictionary",
        "",
        "Every extractable field in the system. A field name is simultaneously the column",
        "header in the corpus register, the `facts.key` it is stored under, and the attribute",
        "on the extraction model. Renaming one renames all three, so rename in `pack.yaml`",
        "and regenerate.",
        "",
    ]
    for m in manifests:
        out += [f"## {m.display_name} (`{m.id}` v{m.version})", ""]
        for doc_type, spec in m.document_types.items():
            out += [
                f"### `{doc_type}`",
                "",
                spec.description + ".",
                "",
                "| Field | Type | Required | Stored in | Meaning |",
                "|---|---|---|---|---|",
            ]
            for f in spec.fields:
                out.append(
                    f"| `{f.name}` | {f.type} | {'yes' if f.required else 'no'} "
                    f"| `facts.{FACT_COLUMN[f.type]}` | {f.description} |"
                )
            out.append("")
    return "\n".join(out)


def _write(path: Path, content: str, check: bool, stale: list[str]) -> None:
    current = path.read_text(encoding="utf-8") if path.exists() else ""
    if current == content:
        return
    if check:
        diff = difflib.unified_diff(
            current.splitlines(),
            content.splitlines(),
            fromfile=f"{path} (committed)",
            tofile=f"{path} (expected)",
            lineterm="",
            n=1,
        )
        stale.append(f"{path}\n" + "\n".join(list(diff)[:20]))
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"wrote {path}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if any generated file is stale")
    args = ap.parse_args()

    pack_dirs = sorted(d for d in PACKS_DIR.iterdir() if (d / "pack.yaml").exists())
    manifests = []
    stale: list[str] = []

    for d in pack_dirs:
        if d.name.startswith("_"):
            continue
        m = load(d)
        if m.id != d.name:
            raise SystemExit(f"{d}/pack.yaml: id {m.id!r} does not match directory name {d.name!r}")
        manifests.append(m)
        _write(d / "schemas.py", render_schemas(m), args.check, stale)
        _write(REGISTER_DIR / f"{m.id}_columns.csv", render_register_columns(m), args.check, stale)

    _write(BATCH_TEMPLATE, render_batch_template(manifests), args.check, stale)
    _write(DICTIONARY, render_dictionary(manifests), args.check, stale)

    if stale:
        print("Generated files are out of date. Run `python -m packs.build` and commit:\n")
        for s in stale:
            print(s, "\n")
        sys.exit(1)
    print(f"{len(manifests)} pack(s) up to date")


if __name__ == "__main__":
    main()
