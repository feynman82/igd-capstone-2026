"""Generate each member's task list from the master task CSV.

    python scripts/build_team_tasks.py            # write team/<slug>/tasks.md
    python scripts/build_team_tasks.py --check    # CI gate: fail if stale

`docs/team-tasks.csv` is the single source of truth for tasks, and it is also the
file imported into Notion. Per-member lists are generated from it so that a task
is written down in exactly one place — the same discipline `packs/build.py`
applies to field names.
"""

from __future__ import annotations

import argparse
import csv
import difflib
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "docs" / "team-tasks.csv"
TEAM_DIR = ROOT / "team"

# Owner as written in the CSV -> directory slug. "All" fans out to everyone.
SLUGS: dict[str, str] = {
    "Christian": "christian",
    "Yew Mun": "yew-mun",
    "Siew": "siew",
    "Zee": "zee",
    "Desmond": "desmond",
}

WEEK_ORDER = [f"W{n}" for n in range(1, 11)]

BANNER = "<!-- GENERATED by `python scripts/build_team_tasks.py`. Edit docs/team-tasks.csv instead. -->"


def _read_rows() -> list[dict[str, str]]:
    with CSV_PATH.open(encoding="utf-8-sig", newline="") as fh:
        return list(csv.DictReader(fh))


def _week_key(week: str) -> int:
    return WEEK_ORDER.index(week) if week in WEEK_ORDER else len(WEEK_ORDER)


def _render(owner: str, slug: str, rows: list[dict[str, str]]) -> str:
    by_week: dict[str, list[dict[str, str]]] = defaultdict(list)
    for row in rows:
        by_week[row["Week"]].append(row)

    shared = sum(1 for r in rows if r["Owner"] == "All")
    lines = [
        BANNER,
        "",
        f"# {owner} — task list",
        "",
        f"{len(rows)} tasks"
        + (f", of which {shared} are shared by the whole team" if shared else "")
        + f". Brief: [`team/{slug}/README.md`](README.md).",
        "",
        "A task is done when its **Done when** column is true — not when it feels finished.",
        "Update `Status` in `docs/team-tasks.csv` and regenerate; do not edit this file.",
        "",
    ]

    for week in sorted(by_week, key=_week_key):
        week_rows = sorted(by_week[week], key=lambda r: (r["Due"], r["Task"]))
        due = week_rows[0]["Due"]
        lines += [f"## {week} — due {due}", ""]
        for row in week_rows:
            done = row["Status"].strip().lower() in {"done", "complete", "completed"}
            box = "[x]" if done else "[ ]"
            tag = " *(whole team)*" if row["Owner"] == "All" else ""
            lines.append(f"- {box} **{row['Task']}**{tag}")
            lines.append(f"  - _Done when:_ {row['Done when']}")
            if row.get("Depends on"):
                lines.append(f"  - _Blocked by:_ {row['Depends on']}")
            lines.append(f"  - _Type:_ {row['Type']} · _Lane:_ {row['Lane']}")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def _write(path: Path, content: str, check: bool) -> bool:
    existing = path.read_text(encoding="utf-8") if path.exists() else ""
    if existing == content:
        return False
    if check:
        rel = path.relative_to(ROOT)
        print(f"STALE: {rel}", file=sys.stderr)
        diff = difflib.unified_diff(
            existing.splitlines(), content.splitlines(), "on disk", "expected", lineterm=""
        )
        for line in list(diff)[:40]:
            print(line, file=sys.stderr)
        return True
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if any list is stale")
    args = parser.parse_args()

    rows = _read_rows()
    unknown = {r["Owner"] for r in rows} - set(SLUGS) - {"All"}
    if unknown:
        print(f"error: unknown owner(s) in the CSV: {sorted(unknown)}", file=sys.stderr)
        return 2

    stale = False
    for owner, slug in SLUGS.items():
        mine = [r for r in rows if r["Owner"] in (owner, "All")]
        stale |= _write(TEAM_DIR / slug / "tasks.md", _render(owner, slug, mine), args.check)

    if args.check and stale:
        print("\nRun `python scripts/build_team_tasks.py` and commit the result.", file=sys.stderr)
        return 1
    if args.check:
        print(f"{len(SLUGS)} task list(s) up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
